class SchemaError(ValueError):
    """The spec cannot be turned into a schema.

    Distinct from `AppSpecError`: the spec is well-formed, but generating a
    database from it is impossible or would be wrong.
    """


# ---------------------------------------------------------------------------
# DDL
# ---------------------------------------------------------------------------

def ddl_for(spec: AppSpec, stack: Stack | None = None) -> str:
    """`CREATE TABLE` statements for `data.local.entities`.

    Returns an empty string for an integration app, which is the correct answer
    rather than an error: there is nothing this app should create.
    """
    stack = stack or stack_for_spec(spec)
    entities = spec.local_entities
    if not entities:
        return ""

    parts = [
        "-- Generated by app-builder from helios-app.yaml. Do not edit by hand:",
        "-- the spec is the source of truth, so change it and regenerate.",
        "",
        "PRAGMA foreign_keys = ON;",
        "",
    ]
    for entity in entities:
        parts.append(_table_ddl(entity, stack))
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def _table_ddl(entity: EntitySpec, stack: Stack) -> str:
    lines: list[str] = []
    has_id = any(f.name == "id" for f in entity.fields)

    for field in entity.fields:
        lines.append(f"    {_col_ddl(field, stack, is_primary=(field.name == 'id'))}")

    if not has_id:
        # No `id` field declared. Every real app declares one, but an entity
        # without a primary key is not addressable by get_<entity>(id), and the
        # CHECK fragments assume a stable row identity. Add the conventional one.
        lines.insert(0, '    "id" TEXT PRIMARY KEY')

    body = ",\n".join(lines)
    return f'CREATE TABLE IF NOT EXISTS "{entity.name}" (\n{body}\n);'


def _col_ddl(field: FieldSpec, stack: Stack, *, is_primary: bool) -> str:
    """One column definition, with its CHECK constraint if the stack defines one."""
    sql_type = stack.sql_type(str(field.type))
    pieces = [f'"{field.name}"', sql_type]

    if is_primary:
        pieces.append("PRIMARY KEY")
    elif field.required:
        # NOT NULL on required fields only. An optional field that is NOT NULL
        # would make a legitimate "we do not know yet" unwritable, and NULL is the
        # honest representation of an absent value — which is also why a fact
        # source returns None for an unknown subject rather than zero.
        pieces.append("NOT NULL")

    fragment = stack.check_for(str(field.type))
    # A primary key is already constrained to be present and unique; a value-shape
    # CHECK on `id TEXT PRIMARY KEY` would be noise, and `id` is typed `string`,
    # which has no fragment anyway.
    if fragment and not is_primary:
        quoted = f'"{field.name}"'
        check = fragment.format(col=quoted)
        if field.required:
            pieces.append(f"CHECK ({check})")
        else:
            # NULL MUST be allowed through, and that is not automatic. A CHECK is
            # satisfied when it evaluates to NULL, but `typeof(col) = 'text'` is
            # FALSE for NULL (typeof(NULL) is 'null'), so the constraint would
            # reject every absent optional value. helios-collect's
            # `last_contacted` is exactly that case.
            pieces.append(f"CHECK ({quoted} IS NULL OR ({check}))")

    return " ".join(pieces)


