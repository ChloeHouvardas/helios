def seed_from_json(conn: sqlite3.Connection, data_dir: Path | str,
                   *, entities: list[EntitySpec] | None = None) -> dict[str, int]:
    """Load `data/<entity>.json` (plural accepted) into the tables.

    Returns `{entity: rows_inserted}`. A file that does not exist is skipped
    rather than an error: a generated app ships with a schema and no data, and
    fixtures arrive later.

    Values go through `_runtime_coerce`, the same rules the generated store uses,
    so a fixture holding a float for a decimal field is refused here with the field
    named — before it becomes a wrong number in the database.
    """
    data_dir = Path(data_dir)
    counts: dict[str, int] = {}

    for entity in (entities or []):
        path = _find_fixture(data_dir, entity.name)
        if path is None:
            counts[entity.name] = 0
            continue

        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            raise SchemaError(
                f"{path} is not valid JSON ({exc}); fix the syntax, then re-seed") from exc

        rows = _rows_from(payload, entity.name, path)
        insert = _store_functions(entity)["insert"]
        inserted = 0
        for row in rows:
            insert(conn, row)
            inserted += 1
        conn.commit()
        counts[entity.name] = inserted

    return counts


def _find_fixture(data_dir: Path, entity: str) -> Path | None:
    """`<entity>.json`, or the naive plural, or None."""
    for candidate in (f"{entity}.json", f"{entity}s.json"):
        path = data_dir / candidate
        if path.exists():
            return path
    return None


def _rows_from(payload: Any, entity: str, path: Path) -> list[dict[str, Any]]:
    """Accept a list of rows, or a mapping holding one under a known key."""
    if isinstance(payload, list):
        rows = payload
    elif isinstance(payload, dict):
        rows = None
        for key in (entity, f"{entity}s", "rows", "records", "items"):
            if isinstance(payload.get(key), list):
                rows = payload[key]
                break
        if rows is None:
            rows = [payload]
    else:
        raise SchemaError(
            f"{path} holds a {type(payload).__name__}; write a JSON list of "
            f"{entity} objects, or a mapping with a `{entity}` list")

    bad = [i for i, r in enumerate(rows) if not isinstance(r, dict)]
    if bad:
        raise SchemaError(
            f"{path}: entries {bad} are not objects; each {entity} must be a JSON "
            "object of field name to value")
    return rows


def _store_functions(entity: EntitySpec) -> dict[str, Any]:
    """Coercion and insertion for one entity, without importing the generated file.

    The scaffolder may seed a database in the same run that generated `store.py`,
    before that file is importable. Coercion comes from `_runtime_coerce`, which is
    the same module whose source is embedded into the generated store, so the two
    paths cannot disagree.
    """
    coerce_value = _runtime_coerce.coerce_value
    types = {f.name: str(f.type) for f in entity.fields}

    def insert(conn: sqlite3.Connection, row: dict[str, Any]) -> None:
        unknown = sorted(set(row) - set(types))
        if unknown:
            raise SchemaError(
                f"{entity.name} has no field(s) {unknown}; write one of "
                f"{sorted(types)}")
        data = {k: coerce_value(types[k], entity.name, k, v) for k, v in row.items()}
        cols = sorted(data)
        sql = (f'INSERT INTO "{entity.name}" '
               f'({", ".join(chr(34) + c + chr(34) for c in cols)}) '
               f'VALUES ({", ".join("?" for _ in cols)})')
        conn.execute(sql, [data[c] for c in cols])

    return {"insert": insert}
