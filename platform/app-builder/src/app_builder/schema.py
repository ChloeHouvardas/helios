"""Generate the SQLite schema and data-access layer from a spec's `data` section.

Three outputs:

* `ddl_for(spec)` — `CREATE TABLE` per entity in `data.local`.
* `store_module_for(spec)` — a standalone `store.py` with `connect()` and typed
  accessors, using parameterised SQL only.
* `seed_from_json(conn, data_dir)` — load `data/*.json` fixtures into the tables.

`data.integration` produces no DDL. Data the app does not own is not created by
it; generating a table for it would produce a second, divergent copy of someone
else's record.

Money and float
---------------
Two separate guards, because one of them cannot be done in SQL.

`decimal` fields become `TEXT` with a CHECK that the value parses as a decimal
string. TEXT round-trips exactly through Python's `Decimal`; REAL would put a
binary float in the database, and a rounding error in an invoice total is a real
financial error rather than a display artefact.

The float guard lives in the coercion code (`_runtime_coerce`), not in the DDL,
and that is not a preference. SQLite applies column affinity *before* a CHECK
constraint runs, so binding the Python float `12.5` into a TEXT column arrives as
the string `'12.5'` and the CHECK passes. No pure-SQL constraint can tell "the
caller passed a decimal string" from "the caller passed a float that happens to
stringify". The coercion therefore refuses a `float` outright, naming the field.

One implementation, embedded
---------------------------
`store.py` is generated into each app, which cannot import `app_builder`. But the
seeder runs inside `app_builder` and needs the identical rules, or a fixture could
be accepted at seed time and refused at write time. So the coercion lives once, in
`_runtime_coerce`, and this module embeds that file's *source text* into the
generated store via `inspect.getsource`. Same code, two places, no drift.

Identifiers are quoted
----------------------
Entity and field names are constrained to `^[a-z_][a-z0-9_]*$` by the spec model,
which excludes most injection — but that pattern still admits SQL keywords like
`order`, `table` and `select`. A spec naming a field `order` is legal and would
otherwise generate DDL that does not parse. Every identifier is emitted as
`"name"`, so a reserved word cannot break the statement.
"""
